def t(key: str, language: LanguageCode = LanguageCode.EN, **kwargs: object) -> str:
    """Resolve a localized UI string with automatic English fallback."""
    table = _CATALOG.get(language, _CATALOG[LanguageCode.EN])
    template = table.get(key) or _CATALOG[LanguageCode.EN].get(key, key)
    if kwargs:
        return template.format(**kwargs)
    return template
